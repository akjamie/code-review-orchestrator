package org.akj.reviewer.eval;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;

public class EvalReport {

    public record CaseEvaluation(
        String caseId,
        String description,
        FindingMatcher.MatchResult matchResult
    ) {}

    private final List<CaseEvaluation> evaluations;

    public EvalReport(List<CaseEvaluation> evaluations) {
        this.evaluations = evaluations != null ? evaluations : List.of();
    }

    public List<CaseEvaluation> getEvaluations() {
        return evaluations;
    }

    public int totalExpected() {
        return evaluations.stream()
            .mapToInt(e -> e.matchResult().hits().size() + e.matchResult().misses().size())
            .sum();
    }

    public int totalHits() {
        return evaluations.stream()
            .mapToInt(e -> e.matchResult().hits().size())
            .sum();
    }

    public int totalMisses() {
        return evaluations.stream()
            .mapToInt(e -> e.matchResult().misses().size())
            .sum();
    }

    public int totalFalsePositives() {
        return evaluations.stream()
            .mapToInt(e -> e.matchResult().falsePositives().size())
            .sum();
    }

    public double calculateRecall() {
        int expected = totalExpected();
        if (expected == 0) return 1.0;
        return (double) totalHits() / expected;
    }

    public double calculatePrecision() {
        int reported = totalHits() + totalFalsePositives();
        if (reported == 0) return 1.0;
        return (double) totalHits() / reported;
    }

    public double calculateF1() {
        double r = calculateRecall();
        double p = calculatePrecision();
        if (p + r == 0.0) return 0.0;
        return 2 * (p * r) / (p + r);
    }

    public String toMarkdown() {
        double recall = calculateRecall();
        double precision = calculatePrecision();
        double f1 = calculateF1();

        StringBuilder sb = new StringBuilder();
        sb.append("# 📊 Code Review Orchestrator - Evaluation Report\n\n");
        sb.append("## Summary Metrics\n\n");
        sb.append(String.format("- **Total Benchmark Cases**: `%d`\n", evaluations.size()));
        sb.append(String.format("- **Recall (召回率)**: `%.1f%%` (%d / %d hits)\n", recall * 100, totalHits(), totalExpected()));
        sb.append(String.format("- **Precision (准确率)**: `%.1f%%` (%d hits / %d reported in target+safe regions)\n",
            precision * 100, totalHits(), totalHits() + totalFalsePositives()));
        sb.append(String.format("- **F1 Score**: `%.2f`\n", f1));
        sb.append(String.format("- **False Positives in Safe Regions**: `%d`\n\n", totalFalsePositives()));

        sb.append("## 📋 Case Breakdown\n\n");
        sb.append("| Case ID | Description | Hits (🎯) | Misses (❌) | False Positives (⚠️) |\n");
        sb.append("|---|---|:---:|:---:|:---:|\n");

        for (var e : evaluations) {
            sb.append(String.format("| `%s` | %s | %d | %d | %d |\n",
                e.caseId(),
                e.description() != null ? e.description() : "-",
                e.matchResult().hits().size(),
                e.matchResult().misses().size(),
                e.matchResult().falsePositives().size()));
        }

        sb.append("\n---\n*Report generated by `org.akj.reviewer.eval.EvalReport`*\n");
        return sb.toString();
    }

    public void writeMarkdownReport(Path outputPath) throws IOException {
        if (outputPath.getParent() != null) {
            Files.createDirectories(outputPath.getParent());
        }
        Files.writeString(outputPath, toMarkdown(), StandardCharsets.UTF_8);
    }

    public void assertThresholds(double minRecall, double minPrecision) {
        double recall = calculateRecall();
        double precision = calculatePrecision();
        if (recall < minRecall || precision < minPrecision) {
            throw new AssertionError(String.format(
                "Evaluation thresholds not met: Recall=%.2f (required >= %.2f), Precision=%.2f (required >= %.2f)",
                recall, minRecall, precision, minPrecision));
        }
    }
}
